#!/usr/bin/env node
/**
 * Pulls documentation out of remote git repositories and normalises it into
 * `src/content/docs/` so Starlight can render it.
 *
 * Remote docs are written for GitHub's markdown renderer, not for Starlight, so
 * this script does the translation:
 *
 *   - injects the frontmatter Starlight requires (title, description, edit URL,
 *     last-updated date taken from the upstream commit history)
 *   - removes the leading heading that became the title, and demotes the rest
 *     when a document would otherwise render two level-one headings
 *   - rewrites relative links between documents to real site URLs, and links to
 *     files that are not published here back to the upstream repository
 *   - replaces a bare GitHub permalink with the code it points at, the way
 *     GitHub renders one in a comment
 *   - copies images and other referenced assets into `public/_assets/`
 *
 * Everything it writes is generated output and is kept out of git.
 *
 * Usage:
 *   node scripts/sync-docs.mjs                 sync every source
 *   node scripts/sync-docs.mjs --source=<id>   sync one source
 *   node scripts/sync-docs.mjs --offline       reuse the clone cache, no fetch
 *   node scripts/sync-docs.mjs --clean         delete generated output + cache
 */

import { execFile } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import posix from 'node:path/posix';
import process from 'node:process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

import { sources } from '../docs.sources.mjs';
import { base } from '../site.config.mjs';

/**
 * @typedef {object} DocSource
 * @property {string} id
 * @property {string} label
 * @property {string} repo
 * @property {string} [ref]
 * @property {string} [path]
 * @property {string} [dest]
 * @property {number} [order]
 * @property {boolean} [collapsed]
 * @property {string[]} [include]
 * @property {string[]} [exclude]
 * @property {string[]} [pages]
 * @property {Record<string, string>} [rename]
 * @property {Record<string, string>} [titles]
 * @property {Record<string, string>} [groups]
 * @property {boolean} [embedCode]
 * @property {string} [url]
 */

const execFileAsync = promisify(execFile);

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CACHE_DIR = path.join(ROOT, '.cache', 'remote');
const DOCS_DIR = path.join(ROOT, 'src', 'content', 'docs');
const ASSETS_DIR = path.join(ROOT, 'public', '_assets');
const GENERATED_DIR = path.join(ROOT, 'src', 'generated');
const BUILD_DIRS = [
  path.join(ROOT, 'dist'),
  path.join(ROOT, '.astro'),
  path.join(ROOT, 'node_modules', '.astro'),
  path.join(ROOT, 'node_modules', '.vite'),
];
const GITIGNORE = path.join(ROOT, '.gitignore');

const PAGE_EXTENSIONS = new Set(['.md', '.mdx', '.markdown', '.mdown', '.mkd']);
const ASSET_EXTENSIONS = new Set([
  '.svg', '.png', '.jpg', '.jpeg', '.gif', '.webp', '.avif', '.ico', '.pdf',
]);

const GITIGNORE_START = '# >>> generated by scripts/sync-docs.mjs -- do not edit';
const GITIGNORE_END = '# <<< generated by scripts/sync-docs.mjs';

// ---------------------------------------------------------------------------
// entry point
// ---------------------------------------------------------------------------

async function main() {
  const args = parseArgs(process.argv.slice(2));

  const selected = args.source
    ? sources.filter((s) => s.id === args.source)
    : sources;

  if (args.source && selected.length === 0) {
    fail(`No source with id "${args.source}". Known ids: ${sources.map((s) => s.id).join(', ')}`);
  }

  if (args.clean) {
    await clean(selected);
    return;
  }

  if (selected.length === 0) {
    console.log('No documentation sources configured in docs.sources.mjs.');
    return;
  }

  const summaries = [];
  for (const source of selected) {
    summaries.push(await syncSource(source, args));
  }

  await updateGitignore(sources);
  await writeManifest(summaries, args);

  console.log('');
  for (const s of summaries) {
    console.log(`  ${s.id}: ${s.pages} pages, ${s.assets} assets from ${s.repo}@${s.shortSha}`);
  }
  console.log('');
}

function parseArgs(argv) {
  const args = { clean: false, offline: false, source: null };
  for (const arg of argv) {
    if (arg === '--clean') args.clean = true;
    else if (arg === '--offline') args.offline = true;
    else if (arg.startsWith('--source=')) args.source = arg.slice('--source='.length);
    else fail(`Unknown argument: ${arg}`);
  }
  return args;
}

async function clean(selected) {
  for (const source of selected) {
    const dest = destOf(source);
    await rm(path.join(DOCS_DIR, dest));
    await rm(path.join(ASSETS_DIR, dest));
    await rm(path.join(CACHE_DIR, source.id));
    console.log(`Removed generated output and cache for ${source.id}`);
  }
  await rm(GENERATED_DIR);

  // Astro and Expressive Code cache generated asset names. Changing the
  // Expressive Code config without clearing these leaves pages pointing at a
  // stylesheet hash that is no longer emitted.
  for (const dir of BUILD_DIRS) await rm(dir);
  console.log('Removed the build output and Astro caches');
}

// ---------------------------------------------------------------------------
// per-source sync
// ---------------------------------------------------------------------------

/** @param {DocSource} source */
async function syncSource(source, args) {
  validateSource(source);

  const dest = destOf(source);
  const ref = source.ref ?? 'main';
  const docsPath = normaliseSourcePath(source.path ?? 'docs');

  console.log(`\nSyncing ${source.id} <- ${source.repo}@${ref}/${docsPath || '.'}`);

  const repoDir = await fetchRepo(source, ref, docsPath, args.offline);
  const sha = await git(repoDir, ['rev-parse', 'HEAD']);

  const sourceRoot = docsPath ? path.join(repoDir, docsPath) : repoDir;
  if (!(await exists(sourceRoot))) {
    fail(`Path "${docsPath}" does not exist in ${source.repo}@${ref}`);
  }

  const files = await collectFiles(sourceRoot, source);
  if (files.length === 0) {
    fail(`No documents found under "${docsPath}" in ${source.repo}@${ref}`);
  }

  // Map every input file to where it lands, before rewriting anything, so link
  // rewriting can see the final location of each target.
  const plan = buildPlan(files, source, dest);

  const pagesOut = path.join(DOCS_DIR, dest);
  const assetsOut = path.join(ASSETS_DIR, dest);
  await rm(pagesOut);
  await rm(assetsOut);

  let assetCount = 0;
  const pages = [];

  const pageEntries = [...plan.entries.values()].filter((entry) => entry.kind === 'page');
  const rawByPath = new Map();
  for (const entry of pageEntries) {
    rawByPath.set(entry.relPath, await fs.readFile(entry.absPath, 'utf8'));
  }

  const embeds = source.embedCode === false
    ? new Map()
    : await resolvePermalinks(rawByPath, repoDir, source);

  for (const entry of plan.entries.values()) {
    if (entry.kind === 'asset') {
      const target = path.join(assetsOut, entry.outRel);
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.copyFile(entry.absPath, target);
      assetCount += 1;
      continue;
    }

    const raw = rawByPath.get(entry.relPath);
    const lastUpdated = await lastCommitDate(repoDir, posix.join(docsPath, entry.relPath));

    const titleOverride = source.titles?.[entry.relPath] ?? null;

    const rendered = renderPage(raw, {
      entry,
      titleOverride,
      embeds,
      plan,
      source,
      dest,
      ref,
      docsPath,
      lastUpdated,
    });

    const target = path.join(pagesOut, entry.outRel);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, rendered.content, 'utf8');
    pages.push({
      title: rendered.title,
      slug: entry.slug,
      url: entry.url,
      dir: entry.dir,
      isIndex: entry.isIndex,
      order: entry.order,
    });
  }

  // Explicitly ordered pages first, then by URL. Sorting by URL puts a
  // directory's index page ahead of its siblings, since its URL is their
  // common prefix.
  pages.sort(
    (a, b) =>
      (a.order ?? Number.MAX_SAFE_INTEGER) - (b.order ?? Number.MAX_SAFE_INTEGER) ||
      a.url.localeCompare(b.url),
  );

  return {
    id: source.id,
    label: source.label,
    repo: source.repo,
    ref,
    path: docsPath,
    dest,
    sha,
    shortSha: sha.slice(0, 7),
    pages: pages.length,
    assets: assetCount,
    entries: pages,
  };
}

function validateSource(source) {
  for (const field of ['id', 'label', 'repo']) {
    if (!source?.[field]) fail(`Source is missing required field "${field}": ${JSON.stringify(source)}`);
  }
  if (!/^[^/\s]+\/[^/\s]+$/.test(source.repo)) {
    fail(`Source "${source.id}" has repo "${source.repo}"; expected "owner/name".`);
  }
}

// ---------------------------------------------------------------------------
// git
// ---------------------------------------------------------------------------

async function fetchRepo(source, ref, docsPath, offline) {
  const repoDir = path.join(CACHE_DIR, source.id);
  const url = remoteUrl(source);
  const alreadyCloned = await exists(path.join(repoDir, '.git'));

  if (offline) {
    if (!alreadyCloned) fail(`--offline was passed but ${source.id} has no clone cache yet.`);
    console.log('  using cached clone (offline)');
    return repoDir;
  }

  if (!alreadyCloned) {
    await rm(repoDir);
    await fs.mkdir(path.dirname(repoDir), { recursive: true });
    // A blobless clone keeps full commit history (needed for per-file dates)
    // while downloading file contents only for the paths actually checked out.
    await git(ROOT, ['clone', '--filter=blob:none', '--no-checkout', '--sparse', url, repoDir]);
  }

  await git(repoDir, ['remote', 'set-url', 'origin', url]);

  if (docsPath) {
    await git(repoDir, ['sparse-checkout', 'set', docsPath]);
  } else {
    await git(repoDir, ['sparse-checkout', 'disable']);
  }

  await git(repoDir, ['fetch', '--filter=blob:none', '--force', 'origin', ref]);
  await git(repoDir, ['checkout', '--force', '--detach', 'FETCH_HEAD']);

  return repoDir;
}

function remoteUrl(source) {
  if (source.url) return source.url;
  const token = process.env.DOCS_SYNC_TOKEN ?? process.env.GITHUB_TOKEN;
  if (token) return `https://x-access-token:${token}@github.com/${source.repo}.git`;
  return `https://github.com/${source.repo}.git`;
}

async function git(cwd, args) {
  try {
    const { stdout } = await execFileAsync('git', args, {
      cwd,
      maxBuffer: 64 * 1024 * 1024,
      env: { ...process.env, GIT_TERMINAL_PROMPT: '0' },
    });
    return stdout.trim();
  } catch (error) {
    const message = String(error?.stderr || error?.message || error);
    fail(`git ${args.map(redact).join(' ')} failed:\n${redact(message)}`);
  }
}

/** Keep access tokens out of logs. */
function redact(text) {
  return String(text).replace(/x-access-token:[^@]+@/g, 'x-access-token:***@');
}

/** Like git(), but returns null instead of aborting the sync. */
async function gitQuiet(cwd, args) {
  try {
    const { stdout } = await execFileAsync('git', args, {
      cwd,
      maxBuffer: 64 * 1024 * 1024,
      env: { ...process.env, GIT_TERMINAL_PROMPT: '0' },
    });
    return stdout;
  } catch {
    return null;
  }
}

async function lastCommitDate(repoDir, repoRelPath) {
  const out = await git(repoDir, ['log', '-1', '--format=%cI', '--', repoRelPath]);
  return out || null;
}

// ---------------------------------------------------------------------------
// file discovery and output planning
// ---------------------------------------------------------------------------

async function collectFiles(root, source) {
  const exclude = (source.exclude ?? []).map(globToRegExp);
  const include = (source.include ?? []).map(globToRegExp);
  const found = [];

  async function walk(dir, prefix) {
    const dirents = await fs.readdir(dir, { withFileTypes: true });
    for (const dirent of dirents.sort((a, b) => a.name.localeCompare(b.name))) {
      if (dirent.name.startsWith('.')) continue;
      const relPath = prefix ? posix.join(prefix, dirent.name) : dirent.name;
      if (exclude.some((re) => re.test(relPath))) continue;

      if (dirent.isDirectory()) {
        await walk(path.join(dir, dirent.name), relPath);
        continue;
      }
      if (!dirent.isFile()) continue;

      const ext = posix.extname(dirent.name).toLowerCase();
      let kind = null;
      if (PAGE_EXTENSIONS.has(ext)) kind = 'page';
      else if (ASSET_EXTENSIONS.has(ext)) kind = 'asset';
      else if (include.some((re) => re.test(relPath))) kind = 'asset';
      if (!kind) continue;

      found.push({ absPath: path.join(dir, dirent.name), relPath, kind });
    }
  }

  await walk(root, '');
  return found;
}

/**
 * Decide the output location and URL of every file up front.
 * Output paths are already slug-shaped, so the URL Astro derives from the file
 * path is exactly the URL computed here.
 */
function buildPlan(files, source, dest) {
  const entries = new Map();
  const order = new Map(
    (source.pages ?? []).map((slugPath, index) => [stripExtension(slugPath), index + 1]),
  );
  const taken = new Map();
  const urls = new Map();

  for (const file of files) {
    const renamed = source.rename?.[file.relPath] ?? file.relPath;

    let outRel;
    if (file.kind === 'page') {
      outRel = `${slugifyPath(stripExtension(renamed))}.md`;
    } else {
      const ext = posix.extname(renamed).toLowerCase();
      outRel = `${slugifyPath(stripExtension(renamed))}${ext}`;
    }

    const clash = taken.get(`${file.kind}:${outRel}`);
    if (clash) {
      fail(
        `Source "${source.id}": "${file.relPath}" and "${clash}" both map to "${outRel}". ` +
          'Use the "rename" option to disambiguate.',
      );
    }
    taken.set(`${file.kind}:${outRel}`, file.relPath);

    const entry = { ...file, outRel };

    if (file.kind === 'page') {
      const slugPath = stripExtension(outRel).replace(/\/index$/, '').replace(/^index$/, '');
      // Starlight applies the base path to sidebar links itself, so the slug is
      // kept separate from the base-prefixed URL used inside page content.
      entry.slug = slugPath ? `${dest}/${slugPath}` : dest;
      entry.url = `${base}/${entry.slug}/`;
      entry.dir = outRel.split('/').slice(0, -1);
      entry.isIndex = posix.basename(outRel) === 'index.md';
      entry.order = order.get(stripExtension(renamed)) ?? order.get(stripExtension(file.relPath)) ?? null;

      const urlClash = urls.get(entry.url);
      if (urlClash) {
        fail(
          `Source "${source.id}": "${file.relPath}" and "${urlClash}" both publish to ` +
            `"${entry.url}". Use the "rename" option to disambiguate.`,
        );
      }
      urls.set(entry.url, file.relPath);
    } else {
      entry.url = `${base}/_assets/${dest}/${outRel}`;
    }

    entries.set(file.relPath, entry);
  }

  return { entries };
}

function slugifyPath(relPath) {
  return relPath
    .split('/')
    .filter(Boolean)
    .map(slugifySegment)
    .join('/');
}

/**
 * Produces a segment that Astro's own slug generation leaves untouched, so the
 * file path and the published URL cannot drift apart.
 */
function slugifySegment(segment) {
  const slug = segment
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return slug || 'untitled';
}

function stripExtension(p) {
  return p.replace(/\.[^./]+$/, '');
}

function globToRegExp(pattern) {
  const escaped = pattern
    .replace(/[.+^${}()|[\]\\]/g, '\\$&')
    .replace(/\*\*\//g, '\u0000')
    .replace(/\*/g, '[^/]*')
    .replace(/\u0000/g, '(?:.*/)?')
    .replace(/\?/g, '[^/]');
  return new RegExp(`^${escaped}$`);
}

// ---------------------------------------------------------------------------
// markdown transformation
// ---------------------------------------------------------------------------

function renderPage(raw, ctx) {
  const { existing, body: withoutFrontmatter } = splitFrontmatter(raw);

  let body = stripLiquidTags(withoutFrontmatter);

  const protectedBody = protectCode(body);

  // A configured title means the document's first heading is a real section
  // rather than the page title, so it has to stay in the body.
  const { title, text: afterTitle } = ctx.titleOverride
    ? { title: ctx.titleOverride, text: protectedBody.text }
    : extractTitle(protectedBody.text);

  let working = afterTitle;

  if (/^#[^#]/m.test(working)) working = demoteHeadings(working);

  working = embedPermalinks(working, ctx);

  const { text: linked, warnings } = rewriteLinks(working, ctx);
  for (const warning of warnings) console.warn(`  ! ${warning}`);

  body = restoreCode(linked, protectedBody.blocks).trim();

  const description = extractDescription(body);
  const frontmatterTitle = title ?? titleFromFilename(ctx.entry.relPath);
  const frontmatter = buildFrontmatter({
    existing,
    title: frontmatterTitle,
    description,
    ctx,
  });

  return { content: `${frontmatter}\n\n${body}\n`, title: frontmatterTitle };
}

function splitFrontmatter(raw) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(raw);
  if (!match) return { existing: null, body: raw };
  return { existing: match[1], body: raw.slice(match[0].length) };
}

function stripLiquidTags(text) {
  // Upstream docs sometimes wrap content in Jekyll's {% raw %} guards, which
  // mean nothing here and would otherwise render as literal text.
  return text.replace(/\{%-?\s*(end)?raw\s*-?%\}\r?\n?/g, '');
}

/** Swap fenced and inline code for placeholders so transforms cannot touch them. */
function protectCode(text) {
  const blocks = [];
  const store = (match) => {
    blocks.push(match);
    return `\u0000CODE${blocks.length - 1}\u0000`;
  };

  let out = text.replace(
    /^[ \t]*(`{3,}|~{3,})[^\n]*\n[\s\S]*?^[ \t]*\1[ \t]*(?=\n|$)/gm,
    store,
  );
  // A fence that is never closed still protects everything to the end of file.
  out = out.replace(/^[ \t]*(`{3,}|~{3,})[^\n]*\n[\s\S]*$/m, store);
  out = out.replace(/(`+)(?:(?!\1)[\s\S])*?\1/g, store);
  return { text: out, blocks };
}

function restoreCode(text, blocks) {
  return text.replace(/\u0000CODE(\d+)\u0000/g, (_, index) => blocks[Number(index)]);
}

function extractTitle(text) {
  const match = /^(#{1,6})[ \t]+(.+?)[ \t]*#*[ \t]*$/m.exec(text);
  if (!match) return { title: null, text };

  // Only treat it as the page title when nothing but blank lines precede it.
  const before = text.slice(0, match.index);
  if (before.trim() !== '') return { title: null, text };

  const title = cleanInline(match[2]);
  const stripped = text.slice(0, match.index) + text.slice(match.index + match[0].length);
  return { title: title || null, text: stripped.replace(/^\s*\n/, '') };
}

function demoteHeadings(text) {
  return text.replace(/^(#{1,5})([ \t]+)/gm, (_, hashes, space) => `#${hashes}${space}`);
}

/**
 * Takes the page description from the document's opening prose.
 *
 * The search stops at the second heading, so a document whose own introduction
 * is a list or a code block gets no description rather than one lifted from an
 * unrelated section further down.
 */
function extractDescription(body) {
  let inFence = false;
  let headings = 0;

  for (const line of body.split('\n')) {
    const trimmed = line.trim();

    if (/^(`{3,}|~{3,})/.test(trimmed)) { inFence = !inFence; continue; }
    if (inFence || trimmed === '') continue;

    if (/^#{1,6}[ \t]/.test(trimmed)) {
      headings += 1;
      if (headings >= 2) return null;
      continue;
    }

    if (/^(>|\||-|\*|\d+\.|<|!\[)/.test(trimmed)) continue;

    const text = cleanInline(trimmed);
    if (text.length < 40) continue;
    return text.length > 160 ? `${text.slice(0, 157).trimEnd()}...` : text;
  }

  return null;
}

/** Reduce inline markdown to plain text for use in frontmatter values. */
function cleanInline(text) {
  return text
    .replace(/\u0000CODE\d+\u0000/g, '')
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/[*_]{1,3}([^*_]+)[*_]{1,3}/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function titleFromFilename(relPath) {
  const stem = stripExtension(posix.basename(relPath));
  return stem
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function buildFrontmatter({ existing, title, description, ctx }) {
  const { source, ref, docsPath, entry, lastUpdated } = ctx;
  const existingKeys = new Set(
    (existing ?? '').split('\n')
      .map((line) => /^([A-Za-z0-9_-]+):/.exec(line)?.[1])
      .filter(Boolean),
  );

  const lines = [];
  if (existing) lines.push(existing.trimEnd());

  const add = (key, value) => {
    if (!existingKeys.has(key) && value !== null && value !== undefined) {
      lines.push(`${key}: ${value}`);
    }
  };

  add('title', JSON.stringify(title));
  add('description', description === null ? null : JSON.stringify(description));
  add('editUrl', `https://github.com/${source.repo}/blob/${ref}/${posix.join(docsPath, entry.relPath)}`);
  add('lastUpdated', lastUpdated);

  if (entry.order !== null && !existingKeys.has('sidebar')) {
    lines.push('sidebar:', `  order: ${entry.order}`);
  }

  return `---\n${lines.join('\n')}\n---`;
}

// ---------------------------------------------------------------------------
// GitHub permalink embedding
// ---------------------------------------------------------------------------

/**
 * A GitHub blob permalink with a line anchor, alone on its line.
 *
 * GitHub expands exactly this shape into a code snippet when it appears in a
 * comment, and upstream authors write it expecting that. A permalink used
 * inside a sentence or as a markdown link stays an ordinary link.
 */
const PERMALINK_LINE =
  /^[ \t]*(https:\/\/github\.com\/([^/\s]+)\/([^/\s]+)\/blob\/([^/\s#]+)\/([^\s#]+)#L(\d+)(?:-L(\d+))?)[ \t]*$/gm;

/** File contents keyed by repo, ref and path, shared across every source. */
const blobCache = new Map();

/** Extensions whose Shiki language id differs from the extension itself. */
const LANGUAGE_BY_EXTENSION = new Map(Object.entries({
  cjs: 'javascript', mjs: 'javascript', js: 'javascript', jsx: 'jsx',
  ts: 'typescript', tsx: 'tsx', py: 'python', rb: 'ruby', rs: 'rust',
  sh: 'bash', bash: 'bash', zsh: 'bash', yml: 'yaml', md: 'markdown',
  kt: 'kotlin', gradle: 'groovy', tf: 'terraform', ps1: 'powershell',
  h: 'c', hpp: 'cpp', cc: 'cpp', cxx: 'cpp', htm: 'html',
}));

/**
 * Fetches every permalink target a source refers to, once each.
 *
 * Targets in the source's own repository are read from the clone cache, which
 * resolves the pinned commit exactly and needs no extra credentials. Anything
 * else is fetched over HTTP.
 */
async function resolvePermalinks(rawByPath, repoDir, source) {
  const wanted = new Map();

  for (const raw of rawByPath.values()) {
    for (const match of raw.matchAll(PERMALINK_LINE)) {
      const [, , owner, repo, ref, filePath] = match;
      wanted.set(`${owner}/${repo}@${ref}:${filePath}`, { owner, repo, ref, filePath });
    }
  }

  if (wanted.size === 0) return new Map();

  const resolved = new Map();
  let fetched = 0;

  for (const [key, target] of wanted) {
    if (blobCache.has(key)) {
      resolved.set(key, blobCache.get(key));
      continue;
    }

    const sameRepo = `${target.owner}/${target.repo}`.toLowerCase() === source.repo.toLowerCase();
    let content = sameRepo
      ? await gitQuiet(repoDir, ['show', `${target.ref}:${target.filePath}`])
      : null;

    if (content === null) content = await fetchRawFile(target);

    if (content === null) {
      console.warn(`  ! could not read ${key}; its permalink stays a plain link`);
    } else {
      fetched += 1;
    }

    blobCache.set(key, content);
    resolved.set(key, content);
  }

  if (fetched > 0) console.log(`  embedded code from ${fetched} permalink target(s)`);
  return resolved;
}

async function fetchRawFile({ owner, repo, ref, filePath }) {
  const url = `https://raw.githubusercontent.com/${owner}/${repo}/${ref}/${filePath}`;
  const token = process.env.DOCS_SYNC_TOKEN ?? process.env.GITHUB_TOKEN;

  try {
    const response = await fetch(url, {
      headers: token ? { Authorization: `Bearer ${token}` } : {},
    });
    return response.ok ? await response.text() : null;
  } catch {
    return null;
  }
}

/** Swap each standalone permalink for the lines of code it points at. */
function embedPermalinks(text, ctx) {
  if (!ctx.embeds || ctx.embeds.size === 0) return text;

  return text.replace(
    PERMALINK_LINE,
    (match, url, owner, repo, ref, filePath, startText, endText) => {
      const file = ctx.embeds.get(`${owner}/${repo}@${ref}:${filePath}`);
      if (!file) return match;

      const lines = file.replace(/\r\n/g, '\n').replace(/\n$/, '').split('\n');
      const start = Number(startText);
      const end = endText ? Number(endText) : start;

      if (!Number.isFinite(start) || start < 1 || start > lines.length || end < start) {
        console.warn(`  ! ${ctx.entry.relPath}: ${url} is out of range for the file`);
        return match;
      }

      const snippet = dedent(lines.slice(start - 1, Math.min(end, lines.length)));
      const language = languageFor(filePath);

      // The fence has to outlast any backtick run inside the code itself.
      const longestRun = Math.max(0, ...[...snippet.join('\n').matchAll(/`+/g)].map((m) => m[0].length));
      const fence = '`'.repeat(Math.max(3, longestRun + 1));

      const meta = [
        language,
        `title="${filePath}"`,
        'showLineNumbers',
        `startLineNumber=${start}`,
      ].filter(Boolean).join(' ');

      // The blank lines keep the block and its caption from being absorbed
      // into whatever paragraph surrounds the original permalink.
      return [
        '',
        `${fence}${meta}`,
        ...snippet,
        fence,
        '',
        `[View on GitHub](${url})`,
        '',
      ].join('\n');
    },
  );
}

/** Drop the indentation the snippet shares, so a nested block starts at column one. */
function dedent(lines) {
  const indents = lines
    .filter((line) => line.trim() !== '')
    .map((line) => /^[ \t]*/.exec(line)[0]);

  if (indents.length === 0) return lines;

  let common = indents[0];
  for (const indent of indents.slice(1)) {
    let i = 0;
    while (i < common.length && i < indent.length && common[i] === indent[i]) i += 1;
    common = common.slice(0, i);
  }

  return common ? lines.map((line) => (line.startsWith(common) ? line.slice(common.length) : line)) : lines;
}

function languageFor(filePath) {
  const name = posix.basename(filePath);
  if (!name.includes('.')) return name.toLowerCase() === 'dockerfile' ? 'dockerfile' : '';
  const ext = posix.extname(name).slice(1).toLowerCase();
  return LANGUAGE_BY_EXTENSION.get(ext) ?? ext;
}

// ---------------------------------------------------------------------------
// link rewriting
// ---------------------------------------------------------------------------

const INLINE_LINK = /(!?)\[((?:[^[\]]|\[[^\]]*\])*)\]\([ \t]*(<[^>\n]*>|[^\s()]+)((?:[ \t]+(?:"[^"]*"|'[^']*'|\([^)]*\)))?)[ \t]*\)/g;
const REFERENCE_LINK = /^([ \t]{0,3}\[[^\]\n]+\]:[ \t]*)(\S+)/gm;

function rewriteLinks(text, ctx) {
  const warnings = [];

  let out = text.replace(INLINE_LINK, (match, bang, label, rawTarget, titlePart) => {
    const angled = rawTarget.startsWith('<') && rawTarget.endsWith('>');
    const target = angled ? rawTarget.slice(1, -1) : rawTarget;
    const replacement = resolveTarget(target, ctx, warnings);
    if (replacement === null) return match;
    const wrapped = /[ ()]/.test(replacement) ? `<${replacement}>` : replacement;
    return `${bang}[${label}](${wrapped}${titlePart ?? ''})`;
  });

  out = out.replace(REFERENCE_LINK, (match, prefix, target) => {
    const replacement = resolveTarget(target, ctx, warnings);
    return replacement === null ? match : `${prefix}${replacement}`;
  });

  return { text: out, warnings };
}

/**
 * Turn one relative markdown target into a URL that works on the built site.
 * Returns null to leave the original target untouched.
 */
function resolveTarget(rawTarget, ctx, warnings) {
  const target = rawTarget.trim();
  if (!target) return null;
  if (target.startsWith('#')) return null;              // same-page anchor
  if (target.startsWith('/')) return null;              // absolute or protocol-relative
  if (/^[a-z][a-z0-9+.-]*:/i.test(target)) return null; // http:, mailto:, ...

  const hashIndex = target.search(/[#?]/);
  const filePart = hashIndex === -1 ? target : target.slice(0, hashIndex);
  const suffix = hashIndex === -1 ? '' : target.slice(hashIndex);
  if (!filePart) return null;

  let decoded;
  try {
    decoded = decodeURIComponent(filePart);
  } catch {
    decoded = filePart;
  }

  const fromDir = posix.dirname(ctx.entry.relPath);
  const resolved = posix.normalize(posix.join(fromDir === '.' ? '' : fromDir, decoded));

  // Published here, as either a page or a copied asset.
  const match = ctx.plan.entries.get(resolved);
  if (match) return `${match.url}${suffix}`;

  // Not published here: point at the file in the upstream repository instead.
  const repoRelative = posix.normalize(posix.join(ctx.docsPath, fromDir === '.' ? '' : fromDir, decoded));
  if (repoRelative.startsWith('..')) {
    warnings.push(`${ctx.entry.relPath}: link "${rawTarget}" escapes ${ctx.source.repo}; left unchanged`);
    return null;
  }

  return `https://github.com/${ctx.source.repo}/blob/${ctx.ref}/${repoRelative}${suffix}`;
}

