/**
 * Synced content is build output. Keep .gitignore in step with the configured
 * sources so a new source can never be committed by accident.
 */
async function updateGitignore(allSources) {
  const dests = [...new Set(allSources.map(destOf))].sort();
  const block = [
    GITIGNORE_START,
    '.cache/',
    'src/generated/',
    ...dests.map((dest) => `src/content/docs/${dest}/`),
    ...dests.map((dest) => `public/_assets/${dest}/`),
    GITIGNORE_END,
  ].join('\n');

  let current = '';
  try {
    current = await fs.readFile(GITIGNORE, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  const startIndex = current.indexOf(GITIGNORE_START);
  const endIndex = current.indexOf(GITIGNORE_END);

  let next;
  if (startIndex !== -1 && endIndex !== -1 && endIndex > startIndex) {
    next = current.slice(0, startIndex) + block + current.slice(endIndex + GITIGNORE_END.length);
  } else {
    next = `${current.replace(/\s*$/, '')}\n\n${block}\n`;
  }

  if (next !== current) {
    await fs.writeFile(GITIGNORE, next, 'utf8');
    console.log('  updated .gitignore');
  }
}

