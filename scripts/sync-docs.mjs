/**
 * Records what each source produced so pages such as the landing page can link
 * to documents that genuinely exist instead of guessing at URLs.
 *
 * A partial sync (`--source=`) updates only its own entry and leaves the rest
 * of a previous manifest in place.
 */
async function writeManifest(summaries, args) {
  const manifestPath = path.join(GENERATED_DIR, 'sources.json');

  let previous = { sources: [] };
  if (args.source) {
    try {
      previous = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
    } catch {
      previous = { sources: [] };
    }
  }

  const byId = new Map((previous.sources ?? []).map((entry) => [entry.id, entry]));
  for (const summary of summaries) {
    byId.set(summary.id, {
      id: summary.id,
      label: summary.label,
      repo: summary.repo,
      ref: summary.ref,
      path: summary.path,
      dest: summary.dest,
      commit: summary.sha,
      pageCount: summary.pages,
      assetCount: summary.assets,
      pages: summary.entries,
    });
  }

  const ordered = sources
    .map((source) => byId.get(source.id))
    .filter(Boolean);

  await fs.mkdir(GENERATED_DIR, { recursive: true });
  await fs.writeFile(
    manifestPath,
    `${JSON.stringify({ syncedAt: new Date().toISOString(), sources: ordered }, null, 2)}\n`,
    'utf8',
  );
}

